"""Train, evaluate and package a landslide classifier.

Run from the backend/ directory:

    python -m ml.train                          # SYNTHETIC data (labelled as such)
    python -m ml.train --data my_inventory.csv  # your own labelled data

Outputs (in ml/artifacts/ by default):
    model.joblib       - fitted scikit-learn Pipeline (preprocessing + classifier)
    model_card.json    - data provenance, metrics computed on a held-out split,
                         environment versions and warnings
    training_data.csv  - the exact dataset used (for reproducibility)

All metrics are computed by this script on held-out data. Nothing is hard-coded.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import platform
import sys
from datetime import datetime, timezone
from pathlib import Path

import joblib
import numpy as np
import pandas as pd
import sklearn
from sklearn.compose import ColumnTransformer
from sklearn.ensemble import GradientBoostingClassifier, RandomForestClassifier
from sklearn.inspection import permutation_importance
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import (
    accuracy_score,
    average_precision_score,
    brier_score_loss,
    confusion_matrix,
    f1_score,
    precision_score,
    recall_score,
    roc_auc_score,
)
from sklearn.model_selection import StratifiedKFold, cross_val_score, train_test_split
from sklearn.pipeline import Pipeline
from sklearn.preprocessing import OneHotEncoder, StandardScaler

from app.services.features import (
    CATEGORICAL_FEATURES,
    FEATURE_COLUMNS,
    FEATURE_SPECS,
    LABEL_COLUMN,
    NUMERIC_FEATURES,
    SOIL_TYPES,
)

from .synthetic import GENERATOR_VERSION, generate_synthetic_dataset

DEFAULT_OUT_DIR = Path(__file__).resolve().parent / "artifacts"
MODEL_FILENAME = "model.joblib"
CARD_FILENAME = "model_card.json"
DATASET_FILENAME = "training_data.csv"
DECISION_THRESHOLD = 0.5
MIN_ROWS = 50
MIN_PER_CLASS = 10

SYNTHETIC_WARNING = (
    "Trained and evaluated on SYNTHETIC data generated by ml/synthetic.py. The metrics "
    "measure how well the model recovers that hand-written generating process. They are "
    "NOT estimates of real-world landslide prediction accuracy. Do not use this model "
    "for operational decisions."
)
REAL_DATA_WARNING = (
    "Metrics come from a random held-out split of the supplied data. Spatial and temporal "
    "autocorrelation can make random splits optimistic; validate on independent regions "
    "and time periods before any operational use."
)


class DatasetError(ValueError):
    """Raised when a supplied training dataset does not match the expected schema."""


def build_candidates(seed: int) -> dict:
    return {
        "logistic_regression": LogisticRegression(max_iter=2000),
        "random_forest": RandomForestClassifier(
            n_estimators=200, min_samples_leaf=5, random_state=seed, n_jobs=1
        ),
        "gradient_boosting": GradientBoostingClassifier(random_state=seed),
    }


def make_pipeline(estimator) -> Pipeline:
    preprocess = ColumnTransformer(
        [
            ("num", StandardScaler(), NUMERIC_FEATURES),
            (
                "cat",
                OneHotEncoder(categories=[list(SOIL_TYPES)], handle_unknown="ignore"),
                CATEGORICAL_FEATURES,
            ),
        ]
    )
    return Pipeline([("preprocess", preprocess), ("model", estimator)])


def validate_dataset(df: pd.DataFrame) -> pd.DataFrame:
    """Check schema, ranges and class balance. Returns the cleaned, column-ordered frame."""
    missing = [c for c in FEATURE_COLUMNS + [LABEL_COLUMN] if c not in df.columns]
    if missing:
        raise DatasetError(f"Missing required columns: {missing}")

    df = df[FEATURE_COLUMNS + [LABEL_COLUMN]].copy()
    if df.isna().any().any():
        bad = df.columns[df.isna().any()].tolist()
        raise DatasetError(f"Missing values in columns: {bad}")

    df["soil_type"] = df["soil_type"].astype(str).str.strip().str.lower()
    unknown = sorted(set(df["soil_type"]) - set(SOIL_TYPES))
    if unknown:
        raise DatasetError(f"Unknown soil_type values {unknown}; allowed: {list(SOIL_TYPES)}")

    for col in NUMERIC_FEATURES:
        df[col] = pd.to_numeric(df[col], errors="raise")
        lo, hi = FEATURE_SPECS[col]["min"], FEATURE_SPECS[col]["max"]
        if (df[col] < lo).any() or (df[col] > hi).any():
            raise DatasetError(f"Column {col} has values outside [{lo}, {hi}]")

    if not set(df[LABEL_COLUMN].unique()) <= {0, 1}:
        raise DatasetError(f"Column {LABEL_COLUMN} must contain only 0 and 1")
    df[LABEL_COLUMN] = df[LABEL_COLUMN].astype(int)

    if len(df) < MIN_ROWS:
        raise DatasetError(f"Need at least {MIN_ROWS} rows, got {len(df)}")
    counts = df[LABEL_COLUMN].value_counts()
    if counts.get(0, 0) < MIN_PER_CLASS or counts.get(1, 0) < MIN_PER_CLASS:
        raise DatasetError(f"Need at least {MIN_PER_CLASS} rows of each class, got {counts.to_dict()}")
    return df


def dataset_sha256(df: pd.DataFrame) -> str:
    return hashlib.sha256(df.to_csv(index=False, lineterminator="\n").encode("utf-8")).hexdigest()


def evaluate(pipe: Pipeline, X: pd.DataFrame, y: pd.Series) -> dict:
    proba = pipe.predict_proba(X)[:, 1]
    pred = (proba >= DECISION_THRESHOLD).astype(int)
    tn, fp, fn, tp = confusion_matrix(y, pred, labels=[0, 1]).ravel()
    return {
        "roc_auc": round(float(roc_auc_score(y, proba)), 4),
        "average_precision": round(float(average_precision_score(y, proba)), 4),
        "brier_score": round(float(brier_score_loss(y, proba)), 4),
        "accuracy": round(float(accuracy_score(y, pred)), 4),
        "precision": round(float(precision_score(y, pred, zero_division=0)), 4),
        "recall": round(float(recall_score(y, pred, zero_division=0)), 4),
        "f1": round(float(f1_score(y, pred, zero_division=0)), 4),
        "decision_threshold": DECISION_THRESHOLD,
        "confusion_matrix": {"tn": int(tn), "fp": int(fp), "fn": int(fn), "tp": int(tp)},
        "n": int(len(y)),
        "positive_rate": round(float(y.mean()), 4),
    }


def baselines(y_train: pd.Series, y_test: pd.Series) -> dict:
    """Trivial reference scores so the model metrics can be read in context."""
    base_rate = float(y_train.mean())
    majority = int(base_rate >= 0.5)
    return {
        "majority_class_accuracy": round(float((y_test == majority).mean()), 4),
        "base_rate_brier_score": round(float(brier_score_loss(y_test, np.full(len(y_test), base_rate))), 4),
        "random_roc_auc": 0.5,
        "average_precision_of_random": round(float(y_test.mean()), 4),
    }


def reference_values(X: pd.DataFrame) -> dict:
    ref = {c: float(X[c].median()) for c in NUMERIC_FEATURES}
    ref["slope_modified"] = int(round(ref["slope_modified"]))
    ref["soil_type"] = str(X["soil_type"].mode().iloc[0])
    return ref


def train(
    df: pd.DataFrame,
    *,
    is_synthetic: bool,
    source_detail: str,
    seed: int = 42,
    test_size: float = 0.2,
    cv_folds: int = 5,
    out_dir: Path = DEFAULT_OUT_DIR,
    command: str | None = None,
) -> dict:
    df = validate_dataset(df)
    X, y = df[FEATURE_COLUMNS], df[LABEL_COLUMN]
    X_train, X_test, y_train, y_test = train_test_split(
        X, y, test_size=test_size, stratify=y, random_state=seed
    )

    cv = StratifiedKFold(n_splits=cv_folds, shuffle=True, random_state=seed)
    candidates = {}
    for name, estimator in build_candidates(seed).items():
        scores = cross_val_score(make_pipeline(estimator), X_train, y_train, cv=cv, scoring="roc_auc")
        candidates[name] = {
            "cv_roc_auc_mean": round(float(scores.mean()), 4),
            "cv_roc_auc_std": round(float(scores.std()), 4),
        }
    best_name = max(candidates, key=lambda n: candidates[n]["cv_roc_auc_mean"])

    pipe = make_pipeline(build_candidates(seed)[best_name])
    pipe.fit(X_train, y_train)
    test_metrics = evaluate(pipe, X_test, y_test)

    perm = permutation_importance(
        pipe, X_test, y_test, scoring="roc_auc", n_repeats=5, random_state=seed, n_jobs=1
    )
    importance = sorted(
        (
            {
                "feature": col,
                "label": FEATURE_SPECS[col]["label"],
                "mean": round(float(perm.importances_mean[i]), 4),
                "std": round(float(perm.importances_std[i]), 4),
            }
            for i, col in enumerate(FEATURE_COLUMNS)
        ),
        key=lambda d: d["mean"],
        reverse=True,
    )

    card = {
        "model_name": best_name,
        "trained_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "is_synthetic": is_synthetic,
        "warning": SYNTHETIC_WARNING if is_synthetic else REAL_DATA_WARNING,
        "data": {
            "source": "synthetic" if is_synthetic else "user-supplied",
            "detail": source_detail,
            "generator_version": GENERATOR_VERSION if is_synthetic else None,
            "n_samples": int(len(df)),
            "n_train": int(len(X_train)),
            "n_test": int(len(X_test)),
            "positive_rate": round(float(y.mean()), 4),
            "sha256": dataset_sha256(df),
            "seed": seed,
        },
        "features": FEATURE_COLUMNS,
        "label": LABEL_COLUMN,
        "candidates": candidates,
        "selection": f"Highest mean {cv_folds}-fold stratified CV ROC-AUC on the training split",
        "test_metrics": test_metrics,
        "baselines": baselines(y_train, y_test),
        "permutation_importance": importance,
        "reference_values": reference_values(X_train),
        "environment": {
            "python": platform.python_version(),
            "scikit_learn": sklearn.__version__,
            "numpy": np.__version__,
            "pandas": pd.__version__,
            "platform": platform.platform(),
        },
        "command": command,
    }

    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    df.to_csv(out_dir / DATASET_FILENAME, index=False, lineterminator="\n")
    joblib.dump(pipe, out_dir / MODEL_FILENAME)
    (out_dir / CARD_FILENAME).write_text(json.dumps(card, indent=2), encoding="utf-8")
    return card


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Train the LandslideGuard ML model.")
    parser.add_argument("--data", type=Path, help="CSV with feature columns + 'landslide' (0/1). "
                        "If omitted, a SYNTHETIC dataset is generated.")
    parser.add_argument("--n-samples", type=int, default=6000, help="Synthetic rows (ignored with --data)")
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--test-size", type=float, default=0.2)
    parser.add_argument("--cv-folds", type=int, default=5)
    parser.add_argument("--out-dir", type=Path, default=DEFAULT_OUT_DIR)
    args = parser.parse_args(argv)

    if args.data:
        df = pd.read_csv(args.data)
        is_synthetic, detail = False, f"{args.data.name}"
    else:
        df = generate_synthetic_dataset(args.n_samples, args.seed)
        is_synthetic = True
        detail = f"ml/synthetic.py {GENERATOR_VERSION}, n_samples={args.n_samples}, seed={args.seed}"

    try:
        card = train(
            df,
            is_synthetic=is_synthetic,
            source_detail=detail,
            seed=args.seed,
            test_size=args.test_size,
            cv_folds=args.cv_folds,
            out_dir=args.out_dir,
            command="python -m ml.train " + " ".join(argv if argv is not None else sys.argv[1:]),
        )
    except DatasetError as exc:
        print(f"Dataset error: {exc}", file=sys.stderr)
        return 2

    m = card["test_metrics"]
    print(f"Data: {card['data']['source']} ({card['data']['detail']}), rows={card['data']['n_samples']}, "
          f"positive rate={card['data']['positive_rate']}")
    for name, c in card["candidates"].items():
        print(f"  CV ROC-AUC {name:<20} {c['cv_roc_auc_mean']:.4f} +/- {c['cv_roc_auc_std']:.4f}")
    print(f"Selected: {card['model_name']}")
    print(f"Held-out test: ROC-AUC={m['roc_auc']} AP={m['average_precision']} Brier={m['brier_score']} "
          f"F1={m['f1']} (n={m['n']})")
    print(f"WARNING: {card['warning']}")
    print(f"Artifacts written to {Path(args.out_dir).resolve()}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
